# а vx шумный: экстраполяция точки падения через ~250 px по вертикали раздувает шум в большие
# ошибки по x — хуже, чем просто следовать за сапогом. Поэтому v1 = follow-x (предсказание
# выключено). Точку падения (predict_landing_x) вернём для угловых бросков, когда появится
# устойчивая оценка скорости (регрессия по N кадрам с отбросом выбросов). См. BACKLOG.
USE_LANDING_PREDICTION = False
MAX_PREDICT_SHIFT_PX = 140  # предохранитель, когда предсказание включено (см. select_target)

