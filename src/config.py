# Мяч считается потерянным (→ перезапуск) только после стольких подряд кадров БЕЗ сапога.
# Детекция кратко пропадает, когда сапог ныряет к тележке (ниже зоны поиска) — это НЕ потеря.
# Реальная потеря = сапог упал, экран ушёл в выбор позиции → отсутствие длится сотни кадров.
# Наблюдение: транзиентные пропуски ≤ 4 кадров; порог 60 (~0.5 с при 117 к/с) с запасом.
