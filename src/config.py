"""Конфигурация бота: пороги детекции, геометрия поля, клавиши.

ВСЕ значения детекции (ROI-соотношения, HSV-пороги) — **первый прикид**, снятый глазами
с двух опорных кадров (пред-запуск и полёт сапога). Их ОБЯЗАТЕЛЬНО валидировать на реально
захваченных кадрах (§3 CLAUDE.md) до заявления «работает». См. BACKLOG.md.
"""

from __future__ import annotations

# --- Область захвата (регион игрового окна) --------------------------------
# None → весь первый монитор (dxcam грабит весь рабочий стол 1920×1080).
# Мини-игра — модальная панель по центру; её геометрия задана абсолютными пикселями
# ниже (REF_*). При игре в окне другого размера — задать (left, top, width, height).
CAPTURE_REGION: tuple[int, int, int, int] | None = None

# --- Геометрия игрового поля (абсолютные пиксели при опорном разрешении) -----
# Измерено по реальному захвату (debug/inspect_frame.py): колонны x≈640/1278,
# HUD до y≈155, тележка у низа. detect_field масштабирует под фактический размер кадра.
REF_W, REF_H = 1920, 1080
FIELD_LEFT_PX = 655
FIELD_TOP_PX = 155
FIELD_RIGHT_PX = 1272
FIELD_BOTTOM_PX = 965

# Верх полосы поиска тележки (абс. пиксели при REF_H). Тележка/её стекло ниже этой линии.
CART_BAND_TOP_PX = 850

# Линия блоков (абс. px при REF_H): ниже неё — открытая нижняя зона, где сапог падает к
# тележке предсказуемо (отскоки только от стенок). Выше — рикошет среди блоков, прицел шумит.
# Измерено по серии: каменный «пол» уровня 1 на y≈605–640; сапог входит в чистый спуск ниже.
BLOCKS_LINE_PX = 640

# --- HSV-пороги (OpenCV: H 0..179, S 0..255, V 0..255) ----------------------
# Тележка. Основной признак центра — бирюзовое «стекло» тележки (симметричные окна):
# его центроид точнее (~центр тележки), чем красный баннер (смещён эмблемой на ~+30 px).
# Бирюза «стекла» = та же, что у сапога (BOOT_TEAL_*), но ищется в нижней полосе.
MIN_CART_GLASS_AREA = 150  # px², крупный блоб стекла
# Красный баннер — резервный признак, если стекло не найдено.
CART_RED_LOW_1 = (0, 120, 110)
CART_RED_HIGH_1 = (10, 255, 255)
CART_RED_LOW_2 = (170, 120, 110)
CART_RED_HIGH_2 = (179, 255, 255)
MIN_CART_AREA = 150  # px², чтобы отсеять красные блики

# Сапог в полёте: холодный бирюзово-голубой блик (заметно светлее тёмно-синего фона).
# TODO(валидация): подтвердить/сузить на реальных кадрах — фон навигацией близок по H.
BOOT_TEAL_LOW = (80, 60, 150)
BOOT_TEAL_HIGH = (105, 255, 255)
# Сапог мелкий: на серии из 200 кадров площадь блоба 21..90. Порог 12 даёт запас на
# кадры у апекса/частично за блоком; ложных срабатываний нет (над полосой тележки в поле
# бирюзы, кроме сапога, не наблюдается).
MIN_BOOT_AREA = 12
# Верхний предел площади сапога. Уровень 2+ вводит БИРЮЗОВЫЕ блоки (та же маска, что у сапога),
# но блок крупный (~854 px), а сапог мелкий (16..90 px). Крупные блобы = блоки, не сапог.
MAX_BOOT_AREA = 200

# --- Управление -------------------------------------------------------------
CONTROL_DEADZONE_PX = 8  # гистерезис, чтобы платформа не «дрожала» на шуме
VELOCITY_SMOOTHING = 0.4  # EMA-вес свежего замера скорости в трекере (меньше → глаже)

# Стратегия. По данным реального спуска (400 кадров) траектория к тележке почти вертикальна,
# а vx шумный: экстраполяция точки падения через ~250 px по вертикали раздувает шум в большие
# ошибки по x — хуже, чем просто следовать за сапогом. Поэтому v1 = follow-x (предсказание
# выключено). Точку падения (predict_landing_x) вернём для угловых бросков, когда появится
# устойчивая оценка скорости (регрессия по N кадрам с отбросом выбросов). См. BACKLOG.
USE_LANDING_PREDICTION = False
MAX_PREDICT_SHIFT_PX = 140  # предохранитель, когда предсказание включено (см. select_target)

# --- Клавиши (движение — A/D, подтверждение/пуск — пробел) -------------------
KEY_LEFT = "a"
KEY_RIGHT = "d"
KEY_LAUNCH = "space"
KEY_KILL = "f12"  # аварийный стоп эмуляции ввода (§10 CLAUDE.md)

# --- Стартовая секвенция -----------------------------------------------------
# Реальная последовательность (из live-теста): пробел (подтвердить старт) → фаза выбора
# направления → пробел (запуск, направление по умолчанию). Позицию тележки на старте
# выбирать не нужно. Паузы подобрать вживую (игра должна успеть сменить фазу).
KEY_TAP_HOLD_S = 0.08       # удержание клавиши при нажатии пробела (мгновенный тап не ловится)
LAUNCH_CONFIRM_PAUSE_S = 0.6  # пауза после «подтвердить старт» до фазы направления
LAUNCH_AFTER_PAUSE_S = 0.4    # пауза после запуска до начала ловли

# Различение «сапог летит» vs «висит в пред-пуске/прицеле».
# В полёте сапог активно движется по ВЕРТИКАЛИ; в прицеле y почти постоянна (двигается только
# по горизонтали). Смотрим разброс y за окно FLIGHT_WINDOW кадров:
#   разброс > FLIGHT_Y_RANGE_PX  → летит (ловим);  иначе → висит (жмём пробел = запуск).
FLIGHT_WINDOW = 24
FLIGHT_Y_RANGE_PX = 25
MIN_FLIGHT_POINTS = 6   # летит, как только накопили столько позиций с разбросом y > порога
# Мяч запускается из состояния LOST (появляется уже летящим). Если сапог «висит» (AIM) и не
# полетел после стольких нажатий пробела — это, скорее всего, ложная детекция (фон уровня),
# перестаём жать (иначе спам «старта»). См. main.
AIM_MAX_SPACES = 2

# «Жать пробел» (запуск/подтверждение/проход экранов между уровнями) — не чаще этого, с.
# Единый механизм: висит сапог → запускаем; нет сапога (меню/переход) → проходим.
LAUNCH_COOLDOWN_S = 0.8

# Нет сапога считается «меню/переход» (можно жать пробел) только после стольких подряд кадров
# без сапога — иначе кратковременный пропуск детекции у тележки спамит пробел.
BALL_LOST_FRAMES = 60

# --- Режим свипа (сбор данных: управляет ли смещение точки касания углом вылета) ---
# Бот ловит сапог, но намеренно ставит тележку так, чтобы касание было со смещением из списка
# (перебор по каждому касанию). follow-x всегда даёт смещение ~0; свип варьирует его → если
# зависимость угла от смещения есть, она проявится в логе (колонка commanded_offset).
SWEEP_OFFSETS = [-40, -20, 0, 20, 40]  # px: целевое смещение boot_x − cart_x в момент касания
SWEEP_ARM_Y_PX = 800  # ниже этой y (при REF_H) считаем, что сапог заходит на касание тележки

# --- Реалтайм ---------------------------------------------------------------
TARGET_LOOP_MS = 16.0  # бюджет цикла захват→детекция→решение→ввод (§7 CLAUDE.md)
